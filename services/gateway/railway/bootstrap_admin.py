"""Create DeerFlow's first admin account from Railway variables.

DeerFlow lets the first visitor of /setup become admin. On a public URL that is
a race, so the Nginx service blocks POST /api/v1/auth/initialize from the
internet and this helper performs the same call over loopback instead, using
DEERFLOW_ADMIN_EMAIL and DEERFLOW_ADMIN_PASSWORD (generated by the template).

Idempotent: once any admin exists, /setup-status reports needs_setup=false and
nothing is sent. It never prints the password or the response body.
"""

from __future__ import annotations

import json
import os
import sys
import time
import urllib.error
import urllib.request

PORT = os.environ.get("PORT", "8001")
BASE = f"http://127.0.0.1:{PORT}"
EMAIL = os.environ.get("DEERFLOW_ADMIN_EMAIL", "").strip()
PASSWORD = os.environ.get("DEERFLOW_ADMIN_PASSWORD", "")
READY_TIMEOUT = float(os.environ.get("DEERFLOW_BOOTSTRAP_TIMEOUT", "1200"))


def log(message: str) -> None:
    print(f"[deerflow-bootstrap] {message}", flush=True)


def request_json(method: str, path: str, payload: dict | None = None) -> tuple[int, dict]:
    data = json.dumps(payload).encode("utf-8") if payload is not None else None
    req = urllib.request.Request(
        f"{BASE}{path}",
        data=data,
        method=method,
        headers={"Content-Type": "application/json", "Accept": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            body = response.read() or b"{}"
            return response.status, json.loads(body)
    except urllib.error.HTTPError as exc:
        return exc.code, {}


def wait_until_ready() -> bool:
    deadline = time.monotonic() + READY_TIMEOUT
    while time.monotonic() < deadline:
        try:
            with urllib.request.urlopen(f"{BASE}/health/ready", timeout=5) as response:
                if response.status == 200:
                    return True
        except Exception:  # noqa: BLE001 - not up yet
            pass
        time.sleep(3)
    return False


def main() -> int:
    if not EMAIL or not PASSWORD:
        log("DEERFLOW_ADMIN_EMAIL / DEERFLOW_ADMIN_PASSWORD not set; skipping admin bootstrap")
        return 0
    if not wait_until_ready():
        log("Gateway did not become ready in time; admin bootstrap skipped (it retries on next start)")
        return 0

    status, body = request_json("GET", "/api/v1/auth/setup-status")
    if status == 200 and body.get("needs_setup") is False:
        log("an admin account already exists; nothing to do")
        return 0

    status, _ = request_json("POST", "/api/v1/auth/initialize", {"email": EMAIL, "password": PASSWORD})
    if status in (200, 201):
        log(f"admin account created: {EMAIL} (password: DEERFLOW_ADMIN_PASSWORD on the Gateway service)")
    elif status == 409:
        log("an admin account already exists; nothing to do")
    elif status in (400, 422):
        log(f"admin bootstrap rejected (HTTP {status}): check that DEERFLOW_ADMIN_EMAIL is a valid address "
            "and DEERFLOW_ADMIN_PASSWORD has at least 8 characters and is not a common password")
    else:
        log(f"admin bootstrap failed (HTTP {status}); it retries on the next start")
    return 0


if __name__ == "__main__":
    sys.exit(main())
